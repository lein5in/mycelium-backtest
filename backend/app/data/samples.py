from dataclasses import dataclass
from datetime import date, datetime
from functools import lru_cache

import numpy as np
import pandas as pd

from app.data.catalog import check_window
from app.data.errors import InvalidSymbolError, OutOfRangeError
from app.data.gaps import gap_report
from app.data.models import DataResult, ProviderInfo, SourceDescriptor
from app.engine.bars import BarSeries, validate_bars
from app.engine.sessions import NS_PER_MINUTE, UsEquitySession, nyse_calendar

PROVIDER = "samples"
DISPLAY_NAME = "Synthetic sample data"
ATTRIBUTION = (
    "SAMPLE DATA: synthetic prices generated by Mycelium Backtest from a fixed seed. "
    "Not real market data."
)
ORIGIN = date(2020, 1, 2)
LAST = date(2030, 12, 31)
TIMEFRAMES = ("1m", "5m")
MAX_RANGE_DAYS = {"1m": 90.0, "5m": 730.0}


@dataclass(frozen=True)
class SampleTicker:
    symbol: str
    seed: int
    start_price: float
    daily_sigma: float
    intraday_sigma: float
    gap_sigma: float
    big_gap_probability: float
    base_volume: float


TICKERS: dict[str, SampleTicker] = {
    ticker.symbol: ticker
    for ticker in (
        SampleTicker("SAMPLE-A", 11, 48.0, 0.012, 0.0009, 0.004, 0.12, 4_000.0),
        SampleTicker("SAMPLE-B", 23, 135.0, 0.018, 0.0013, 0.006, 0.18, 2_500.0),
        SampleTicker("SAMPLE-C", 37, 410.0, 0.009, 0.0007, 0.003, 0.08, 1_200.0),
    )
}


@lru_cache(maxsize=1)
def _sessions() -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    calendar = nyse_calendar()
    labels = calendar.sessions_in_range(pd.Timestamp(ORIGIN), pd.Timestamp(LAST))
    opens = calendar.opens.loc[labels].dt.as_unit("ns").astype("int64").to_numpy()
    closes = calendar.closes.loc[labels].dt.as_unit("ns").astype("int64").to_numpy()
    return labels.as_unit("ns").asi8, opens, closes


@lru_cache(maxsize=8)
def _daily_path(symbol: str) -> tuple[np.ndarray, np.ndarray]:
    ticker = TICKERS[symbol]
    count = _sessions()[0].size
    rng = np.random.default_rng([ticker.seed, 0])
    gaps = rng.normal(0, ticker.gap_sigma, count)
    big = rng.random(count) < ticker.big_gap_probability
    gaps = np.where(big, rng.choice([-1.0, 1.0], count) * rng.uniform(0.006, 0.03, count), gaps)
    days = rng.normal(0.0002, ticker.daily_sigma, count)
    opens = np.empty(count)
    closes = np.empty(count)
    previous = ticker.start_price
    for i in range(count):
        opens[i] = previous * np.exp(gaps[i])
        closes[i] = opens[i] * np.exp(days[i] - 0.35 * gaps[i])
        previous = closes[i]
    return opens, closes


def _volume_profile(count: int) -> np.ndarray:
    x = (np.arange(count) + 0.5) / count
    return 0.55 + 3.2 * (x - 0.5) ** 2 + 0.6 * np.exp(-((x - 0.02) ** 2) / 0.0008)


def _session_minutes(symbol: str, position: int, count: int) -> np.ndarray:
    ticker = TICKERS[symbol]
    day_open, day_close = (path[position] for path in _daily_path(symbol))
    rng = np.random.default_rng([ticker.seed, 1, position])
    steps = rng.normal(0, ticker.intraday_sigma, count)
    walk = np.cumsum(steps)
    bridge = walk - np.arange(1, count + 1) / count * walk[-1]
    log_close = np.log(day_open) + np.arange(1, count + 1) / count * np.log(day_close / day_open)
    close = np.exp(log_close + bridge)
    open_ = np.r_[day_open, close[:-1]]
    wick = np.abs(rng.normal(0, ticker.intraday_sigma * 0.8, (2, count)))
    high = np.maximum(open_, close) * (1 + wick[0])
    low = np.minimum(open_, close) * (1 - wick[1])
    volume = np.round(ticker.base_volume * _volume_profile(count) * rng.lognormal(0, 0.35, count))
    return np.column_stack([open_, high, low, close, volume])


def _aggregate(rows: np.ndarray, size: int) -> np.ndarray:
    groups = rows.shape[0] // size
    trimmed = rows[: groups * size].reshape(groups, size, 5)
    return np.column_stack(
        [
            trimmed[:, 0, 0],
            trimmed[:, :, 1].max(axis=1),
            trimmed[:, :, 2].min(axis=1),
            trimmed[:, -1, 3],
            trimmed[:, :, 4].sum(axis=1),
        ]
    )


def sample_frame(symbol: str, timeframe: str, first: pd.Timestamp, last: pd.Timestamp):
    _, opens, closes = _sessions()
    minutes = 1 if timeframe == "1m" else 5
    frames = []
    for position in np.flatnonzero((closes > first.value) & (opens < last.value)).tolist():
        count = int((closes[position] - opens[position]) // NS_PER_MINUTE)
        rows = _session_minutes(symbol, position, count)
        if minutes > 1:
            rows = _aggregate(rows, minutes)
        stamps = opens[position] + np.arange(rows.shape[0]) * minutes * NS_PER_MINUTE
        frames.append((stamps, rows))
    if not frames:
        raise OutOfRangeError("No NYSE session falls inside this range.", PROVIDER)
    stamps = np.concatenate([s for s, _ in frames])
    rows = np.concatenate([r for _, r in frames])
    keep = (stamps >= first.value) & (stamps < last.value)
    index = pd.DatetimeIndex(stamps[keep].astype("datetime64[ns]")).tz_localize("UTC")
    return pd.DataFrame(rows[keep], index=index, columns=["open", "high", "low", "close", "volume"])


def sample_bars(symbol: str, timeframe: str, start: datetime, end: datetime) -> BarSeries:
    return fetch_sample(symbol, timeframe, start, end).bars


def fetch_sample(symbol: str, timeframe: str, start: datetime, end: datetime) -> DataResult:
    if symbol not in TICKERS:
        offered = ", ".join(TICKERS)
        raise InvalidSymbolError(f"Sample sets are {offered}.", PROVIDER)
    window = check_window(
        start,
        end,
        timeframe,
        TIMEFRAMES,
        PROVIDER,
        pd.Timestamp(LAST, tz="UTC"),
        MAX_RANGE_DAYS,
    )
    if window.start < pd.Timestamp(ORIGIN, tz="UTC"):
        raise OutOfRangeError(f"Sample sets start on {ORIGIN.isoformat()}.", PROVIDER)
    bars = validate_bars(sample_frame(symbol, timeframe, window.start, window.end), timeframe)
    return DataResult(
        bars=bars,
        source=SourceDescriptor(
            provider=PROVIDER,
            display_name=DISPLAY_NAME,
            terms_url=None,
            attribution=ATTRIBUTION,
            mode="SAMPLE DATA",
            symbol=symbol,
            market="us_equity",
            timeframe=timeframe,
            start=window.start.to_pydatetime(),
            end=window.end.to_pydatetime(),
        ),
        gaps=gap_report(bars.ts_ns, timeframe, UsEquitySession()),
    )


def info() -> ProviderInfo:
    return ProviderInfo(
        id=PROVIDER,
        display_name=DISPLAY_NAME,
        kind="sample",
        enabled=True,
        markets=["us_equity"],
        timeframes=list(TIMEFRAMES),
        max_range_days=MAX_RANGE_DAYS,
        symbols=list(TICKERS),
        terms_url=None,
        attribution=ATTRIBUTION,
        mode="SAMPLE DATA",
        note=(
            f"Synthetic US regular-session bars on the NYSE calendar from {ORIGIN.isoformat()} "
            f"to {LAST.isoformat()}, with holidays, early closes, a U-shaped intraday volume "
            "profile and overnight gaps. Deterministic: the same range always gives the same bars."
        ),
    )
